#!/usr/bin/env python3
"""Build Scope: a live oscilloscope on the pedal screen (MS-70CDR 2.10), on zvis."""
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
from zvis_build import Canvas, raw, c_bytes, dials, encode_zoom_rle, build  # noqa: E402

PLOT_H = 36                       # plot rows 0..35; labels at 38; knob boxes at 46


def background(title=False):
    c = Canvas()
    c.rect(0, 0, 127, PLOT_H - 1)
    for x in range(4, 124, 4):
        c.px(x, PLOT_H // 2)
    dials(c, ("TIME", "GAIN", "MODE"))
    if title:
        c.draw_text("SCOPE", 64 - 19, 5, scale=2)
    return c


(HERE / "scope_art.h").write_text("/* generated by build.py */\n#define SCOPE_PLOT_H %du\n" % PLOT_H
                                  + c_bytes("SCOPE_BG", raw(background())))
build(HERE, encode_zoom_rle(background(title=True)))
