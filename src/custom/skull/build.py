#!/usr/bin/env python3
"""Build Skull v0.03: a shaded three-quarter skull that reacts to the signal
(MS-70CDR 2.10), on zvis.

skull3d.py renders our own 3D skull model, lit and dithered to 1 bit, at
JAW_STEPS jaw openings; each becomes a full frame with the black panel and the
dial outlines. The C code picks a frame by level, shifts the panel for the
shake, and adds the eye lights at the sockets' projected positions.
"""
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE.parent / "common"), str(HERE)]
from zvis_build import Canvas, raw, c_bytes, fill, encode_zoom_rle, build  # noqa: E402
import skull3d as S  # noqa: E402

PANEL = 63                         # full screen: the knob boxes are hidden at run time
CAM = dict(scale=0.0178, cy=31)    # skull fills the screen height
CX, CY = 62, 30                    # blast centre
JAW_STEPS = 6
JAW_MAX = 0.34                      # radians, fully open


def frame(jaw):
    c = Canvas()
    fill(c, 0, 0, 127, PANEL)
    img, _ = S.render(jaw=jaw, h=64, **CAM)
    bone = S.dither(S.tone(img), "bayer")
    for y in range(bone.shape[0]):
        for x in range(128):
            if bone[y, x]:
                c.px(x, y, 0)                      # bone is white on the black panel
    return c


frames = [frame(JAW_MAX * k / (JAW_STEPS - 1)) for k in range(JAW_STEPS)]


def fragments(c, n=104, seed=7):
    """Explosion: 2x2 chunks of the skull's lit bone, each with a velocity
    outward from the skull's centre (pixels/frame, x16), aspect-corrected."""
    import random
    rnd = random.Random(seed)
    cells = []
    for y in range(0, PANEL - 1, 2):
        for x in range(0, 127, 2):
            lit = sum(1 for dy in (0, 1) for dx in (0, 1) if not c.pixels[y + dy][x + dx])
            if lit >= 2:
                cells.append((x, y))
    rnd.shuffle(cells)
    cells = sorted(cells[:n])
    cx, cy = CX, CY
    out = []
    for x, y in cells:
        dx, dy = x - cx, (y - cy) * 1.4
        dist = max(1.0, (dx * dx + dy * dy) ** 0.5)
        speed = rnd.uniform(1.0, 2.8)
        vx = dx / dist * speed + rnd.uniform(-0.4, 0.4)
        vy = (dy / dist * speed) / 1.4 - rnd.uniform(0.3, 1.0)       # a little upward kick
        out.append((x, y, max(-127, min(127, round(vx * 16))), max(-127, min(127, round(vy * 16)))))
    return out


frag = fragments(frames[0])
eyes = [S.project((sx * 0.17, -0.03, 0.34), **CAM) for sx in (-1, 1)]
hdr = ["/* generated by build.py: our own 3D skull (skull3d.py), dithered */",
       f"#define SKULL_FRAGS {len(frag)}u", f"#define SKULL_CX {CX}", f"#define SKULL_CY {CY}",
       f"#define SKULL_JAW_STEPS {JAW_STEPS}u", f"#define SKULL_PANEL {PANEL}",
       f"#define SKULL_EYE_LX {eyes[0][0]}", f"#define SKULL_EYE_LY {eyes[0][1]}",
       f"#define SKULL_EYE_RX {eyes[1][0]}", f"#define SKULL_EYE_RY {eyes[1][1]}"]
import math
cos64 = [round(127 * math.cos(2 * math.pi * k / 64)) for k in range(64)]
signed = lambda v: v & 0xFF
(HERE / "skull_art.h").write_text("\n".join(hdr) + "\n" + c_bytes("SKULL_FRAMES", b"".join(raw(f) for f in frames))
                                  + c_bytes("SKULL_FX", bytes(f[0] for f in frag)) + c_bytes("SKULL_FY", bytes(f[1] for f in frag))
                                  + c_bytes("SKULL_FVX", bytes(signed(f[2]) for f in frag))
                                  + c_bytes("SKULL_FVY", bytes(signed(f[3]) for f in frag))
                                  + c_bytes("SKULL_COS64", bytes(signed(v) for v in cos64)))
print("eye lights at", eyes)
build(HERE, encode_zoom_rle(frames[0]))
